"""Resume tailor contracts: the data shapes every tailor lane builds against.

Design: docs/architecture/tailor_design.md (KA-4). Written by the architect;
engineers do not edit this file (a change goes back to the architect, and a
breaking one gets an ADR).

Rules for this module:
  - Standard library only, no I/O. It is imported by the stage (`tailor/`),
    the orchestrators (`tailor_flow.py`, `apply_flow.py`), the CLI and the web
    layer (the one tailor module web/ may import).
  - Data, enums and trivial derived properties only.
  - No personal data in defaults, docstrings or examples: the repo is public.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import Iterator, Optional

CONTRACT_VERSION = 1

# PRD F-21: JD keyword coverage weights.
WEIGHT_REQUIRED = 2
WEIGHT_PREFERRED = 1


# --------------------------------------------------------------------------
# Master resume (design §3)
# --------------------------------------------------------------------------

class SectionKind(str, Enum):
    SUMMARY = "summary"
    EXPERIENCE = "experience"
    EDUCATION = "education"
    PROJECTS = "projects"
    SKILLS = "skills"
    LEADERSHIP = "leadership"
    AWARDS = "awards"
    CERTIFICATIONS = "certifications"
    OTHER = "other"


# Section kinds whose bullets may be rewritten by the model (design §7.2).
REWRITABLE_KINDS = frozenset({SectionKind.EXPERIENCE, SectionKind.PROJECTS,
                              SectionKind.LEADERSHIP})


@dataclass(frozen=True)
class Bullet:
    id: int            # unique across the whole master, assigned by code (1..n in reading order)
    text: str          # verbatim from the resume, bullet glyph removed


@dataclass
class Entry:
    """One job, degree, project or role. Every field except `bullets` is
    protected: copied verbatim into the output and never sent for rewriting."""
    id: str                       # "e1", "e2"... in reading order
    title: str = ""               # job title / degree / project name
    organisation: str = ""        # employer / institution
    location: str = ""
    dates: str = ""               # verbatim, e.g. "May 2024 – Aug 2024"
    subtitle: str = ""            # a second header line (e.g. major, grade), verbatim
    bullets: list[Bullet] = field(default_factory=list)


@dataclass
class Section:
    heading: str                  # verbatim heading in the source
    kind: SectionKind
    entries: list[Entry] = field(default_factory=list)
    items: list[str] = field(default_factory=list)   # SKILLS / AWARDS-style lines, verbatim


@dataclass
class Contact:
    name: str = ""
    email: str = ""
    phone: str = ""
    location: str = ""
    links: list[str] = field(default_factory=list)


@dataclass
class MasterResume:
    resume_hash: str              # resume_ingest.file_hash of the source file
    source_name: str              # "resume.pdf" | "resume.docx" (file name only)
    contact: Contact
    summary: str = ""             # "" when the resume has none
    sections: list[Section] = field(default_factory=list)
    page_count: int = 1           # the owner's page ceiling (F-23)
    parsed_by: str = ""           # model id
    parsed_at: str = ""           # UTC, store.TIME_FMT

    def entries(self) -> Iterator[tuple[Section, Entry]]:
        for s in self.sections:
            for e in s.entries:
                yield s, e

    def bullets(self) -> Iterator[tuple[Entry, Bullet]]:
        for _s, e in self.entries():
            for b in e.bullets:
                yield e, b

    def skills(self) -> list[str]:
        return [i for s in self.sections if s.kind is SectionKind.SKILLS for i in s.items]


# --------------------------------------------------------------------------
# JD terms and mapping (design §4, §5)
# --------------------------------------------------------------------------

class TermStatus(str, Enum):
    PRESENT_EXACT = "present_exact"       # the JD spelling occurs in the resume
    PRESENT_VARIANT = "present_variant"   # an alias (or a curated instance) occurs instead
    MISSING = "missing"


@dataclass
class JdTerm:
    term: str                     # the JD's own spelling (first occurrence)
    canonical: str                # aliases.yaml canonical, else the term lowercased
    required: bool
    source: str = "dictionary"    # dictionary | llm | both
    status: TermStatus = TermStatus.MISSING
    variant: str = ""             # PRESENT_VARIANT: the resume's surface form (e.g. "k8s")
    via: str = ""                 # PRESENT_VARIANT: "alias" | "instance" | "acronym"
    related: str = ""             # MISSING: a resume term it contains/extends (e.g. "Spring" for "Spring Boot")
    attested: bool = False        # the owner said "I have this"

    @property
    def weight(self) -> int:
        return WEIGHT_REQUIRED if self.required else WEIGHT_PREFERRED


# --------------------------------------------------------------------------
# Rewrite and validation (design §6, §7, §8)
# --------------------------------------------------------------------------

class IssueCode(str, Enum):
    NUMBER_ADDED = "number_added"
    NUMBER_DROPPED = "number_dropped"
    FACT_ADDED = "fact_added"
    FACT_DROPPED = "fact_dropped"
    KEYWORD_UNSUPPORTED = "keyword_unsupported"
    LENGTH = "length"
    ID_MISSING = "id_missing"
    ID_UNKNOWN = "id_unknown"
    ID_DUPLICATE = "id_duplicate"
    EMPTY = "empty"
    MODEL_ERROR = "model_error"           # call failed or unreadable: whole entry falls back
    PAGE_TRIM = "page_trim"               # a bullet dropped to keep the page ceiling
    PDF_UNAVAILABLE = "pdf_unavailable"
    ROUNDTRIP = "roundtrip"               # a heading, employer or date did not survive the file


@dataclass(frozen=True)
class ValidationIssue:
    code: IssueCode
    bullet_id: Optional[int] = None       # None for summary/resume-wide issues
    detail: str = ""                      # the offending token(s); never a whole bullet


@dataclass
class BulletChange:
    bullet_id: int
    entry_id: str
    before: str                           # master text
    after: str                            # text in the output ("" when trimmed)
    source: str                           # unchanged | swap | llm | fallback | trimmed
    keywords_used: list[str] = field(default_factory=list)
    issues: list[ValidationIssue] = field(default_factory=list)


class TailorStatus(str, Enum):
    DRAFT = "draft"
    SENT = "sent"
    FAILED = "failed"


@dataclass
class TailorResult:
    job_id: str
    ok: bool
    status: TailorStatus
    mode: str = "deterministic"           # deterministic | llm
    tailored_id: Optional[int] = None     # tailored.id
    docx_path: Optional[str] = None
    pdf_path: Optional[str] = None
    coverage_before: float = 0.0          # 0..1
    coverage_after: float = 0.0
    title_match: bool = False             # the JD title is the headline
    terms: list[JdTerm] = field(default_factory=list)
    changes: list[BulletChange] = field(default_factory=list)
    summary_before: str = ""
    summary_after: str = ""
    skills_after: list[str] = field(default_factory=list)
    issues: list[ValidationIssue] = field(default_factory=list)
    knockouts: list[str] = field(default_factory=list)   # JD lines that read as application questions
    model: str = ""
    error: str = ""                       # failure reason (no resume text)

    @property
    def missing(self) -> list[JdTerm]:
        return [t for t in self.terms if t.status is TermStatus.MISSING]
