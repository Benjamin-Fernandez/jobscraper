# A Playwright `Page`. Typed loosely so this module stays standard-library only.
BrowserPage = Any


@dataclass
class AttemptContext:
    """Per-attempt services the orchestrator hands an adapter."""
    attempt_id: int
    job: dict[str, Any]                       # store.get_job row plus company name/provider/slug
    tenant: Tenant
    dry_run: bool
    email: str                                # the profile's email (account and mail matching)
    resume_path: str
    log: Callable[[str], None]                # one line, no personal values
    screenshot: Callable[[BrowserPage, str], str]   # (page, step) -> saved path
    deadline: float                           # time.monotonic() value after which the attempt fails
    http: Any = None                          # net.HttpClient, for schema adapters


@dataclass
class StepResult:
    """What `next_step` reports after clicking Next/Continue."""
    step: str                       # the step now shown
    is_review: bool = False         # the final page whose primary button submits
    errors: tuple[str, ...] = ()    # visible validation messages (no values)


@runtime_checkable
class AtsAdapter(Protocol):
    """One applicant tracking system. Implementations live in apply/ats/<name>.py
    and register in apply/ats/__init__.py REGISTRY (design §9, §15)."""

    name: str                         # registry key, equals watchlist provider
    needs_account: bool               # Workday: True
    password_rules: PasswordRules
    mail_domains: tuple[str, ...]     # sender domains for verification mail
    otp_pattern: str                  # regex with one group for an emailed code

    def match_url(self, url: str) -> Optional[Tenant]:
        """The tenant if this URL is one of this ATS's posting or apply URLs."""
        ...

    def tenant_from_company(self, job: dict[str, Any]) -> Optional[Tenant]:
        """The tenant from the watchlist provider/slug and the job row."""
        ...

    def plan_from_schema(self, ctx: AttemptContext) -> Optional[FormPlan]:
        """A full plan before the browser opens (Greenhouse), else None.
        Raises ApplyFailure(POSTING_CLOSED) on a 404/410."""
        ...

    def open(self, page: BrowserPage, ctx: AttemptContext) -> None:
        """Navigate to the apply form (or the account wall). Raises
        ApplyFailure(POSTING_CLOSED / PAGE_UNRECOGNISED)."""
        ...

    def account_wall(self, page: BrowserPage) -> Optional[str]:
        """"sign_in" | "sign_up" if the page asks for an account, else None."""
        ...

    def sign_in(self, page: BrowserPage, ctx: AttemptContext, password: Secret) -> None:
        """Raises ApplyFailure(LOGIN_FAILED) on a rejected password."""
        ...

    def sign_up(self, page: BrowserPage, ctx: AttemptContext, password: Secret) -> str:
        """Fill and submit the sign-up form; the password is already in the
        vault. Returns "signed_in" | "verify_email" | "sign_in"."""
        ...

    def enter_code(self, page: BrowserPage, ctx: AttemptContext, code: str) -> None:
        ...

    def read_step(self, page: BrowserPage, ctx: AttemptContext) -> tuple[str, list[FormField]]:
        """The current step id and its fields (DOM adapters; schema adapters
        return the plan's fields that are on the page)."""
        ...

    def fill(self, page: BrowserPage, ctx: AttemptContext,
             fields: Sequence[FormField], answers: dict[str, Answer]) -> list[str]:
        """Fill every answer that `fills`. Returns keys that would not take
        their value (they become FILL_FAILED)."""
        ...

    def next_step(self, page: BrowserPage, ctx: AttemptContext) -> StepResult:
        """Click Next on a wizard (single-page adapters return is_review=True
        without clicking)."""
        ...

    def submit(self, page: BrowserPage, ctx: AttemptContext) -> None:
        """Click the final Submit. Called once per attempt (plus once more only
        after an emailed security code, design §4.2)."""
        ...

    def after_submit(self, page: BrowserPage, ctx: AttemptContext) -> Optional[str]:
        """Poll once: "confirmed:<signal>" | "code_required" | "errors" | None
        (nothing yet). The orchestrator loops until the confirm timeout."""
        ...

    def visible_errors(self, page: BrowserPage) -> tuple[str, ...]:
        ...


