"""Auto-apply contracts: the data shapes every apply lane builds against.

Design: docs/architecture/apply_design.md (KA-1, KA-2, KA-3). Written by the
architect; engineers do not edit this file (a change goes back to the
architect, and a breaking one gets an ADR).

Rules for this module:
  - Standard library only. It is imported by the stage (`apply/`), the
    orchestrator (`apply_flow.py`), the CLI and the web layer (the one stage
    module web/ may import, see the design's layering section), so it must
    pull in nothing heavy and do no I/O.
  - Data, enums and Protocols only. The only behaviour allowed is trivial
    derived properties and the `TRANSITIONS` table.
  - Never put a password or a personal value in a default, a docstring or an
    example here: the repo is public.
"""
