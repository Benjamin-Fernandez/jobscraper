class AnswerTier(IntEnum):
    """Resolver tiers in PRD F-32 order. The first tier that answers wins."""
    NONE = 0
    FIELD_MAP = 1
    PROFILE_RULE = 2
    MEMORY = 3
    DECLARATION = 4
    LLM = 5


class AnswerStatus(str, Enum):
    FILLED = "filled"                   # a value to fill (or filled)
    BLANK_OPTIONAL = "blank_optional"   # optional, no grounded answer: left blank
    SKIPPED = "skipped"                 # hidden, or an alternative input not used
    UNKNOWN = "unknown"                 # no tier answered
    UNGROUNDED = "ungrounded"           # tier 5 answered, grounding check failed
    FILL_FAILED = "fill_failed"         # resolved, but the page would not take it


Value = Union[str, list[str], None]


@dataclass
class Answer:
    field_key: str
    value: Value                      # str; list[str] for MULTI_CHOICE; a path for FILE; None when blank
    tier: AnswerTier
    source: str                       # e.g. "field_map:first_name", "profile:availability.notice_period_days",
                                      # "memory:<label_norm>", "declaration:pep", "llm"
    confidence: float
    status: AnswerStatus = AnswerStatus.FILLED
    option_labels: tuple[str, ...] = ()   # the chosen options' verbatim labels (choice fields)
    rule_id: str = ""                 # questions.yaml key, declaration label, memory key
    model: str = ""                   # tier 5 only
    prompt_hash: str = ""             # tier 5 only: sha256 of system+user, first 16 hex
    sensitive: bool = False           # an S field (design §5.3): never sent to the model, never logged
    note: str = ""                    # why it is UNKNOWN / UNGROUNDED (no personal values)

    @property
    def fills(self) -> bool:
        return self.status is AnswerStatus.FILLED and self.value not in (None, "", [])


