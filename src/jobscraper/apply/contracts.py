@dataclass(frozen=True)
class Tenant:
    ats: str           # greenhouse | lever | ashby | workday
    host: str          # e.g. "<tenant>.wd3.myworkdayjobs.com", "job-boards.greenhouse.io"
    board: str         # Greenhouse board token, Lever/Ashby slug, Workday tenant
    site: str = ""     # Workday site (e.g. "External"); "" elsewhere
    posting_id: str = ""

    @property
    def vault_service(self) -> str:
        """Windows Credential Manager target name (PRD F-35)."""
        return f"jobscraper:{self.ats}:{self.host.lower()}"


@dataclass(frozen=True)
class PasswordRules:
    length: int = 20
    min_length: int = 8
    max_length: int = 64
    need_upper: bool = True
    need_lower: bool = True
    need_digit: bool = True
    need_symbol: bool = True
    symbols: str = "!@#$%^&*-_=+?"


class Secret:
    """A string that never prints. Hand passwords around only inside one."""
    __slots__ = ("_v",)

    def __init__(self, value: str):
        self._v = value

    def reveal(self) -> str:
        return self._v

    def __repr__(self) -> str:
        return "Secret(***)"

    __str__ = __repr__


@dataclass(frozen=True)
class Verification:
    """What the mail fetcher found for a waiting attempt."""
    kind: str             # "link" | "code"
    value: str            # the URL or the code; never logged (log kind + sender domain only)
    sender_domain: str
    received_at: str      # UTC, store.TIME_FMT


