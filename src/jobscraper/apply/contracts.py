@dataclass
class AttemptResult:
    attempt_id: int
    job_id: str
    state: AttemptState
    reason: Optional[ReasonCode] = None
    reason_detail: str = ""
    step: str = ""
    url: str = ""                 # page URL at the end (query string dropped)
    confirmation: str = ""        # the signal that matched, e.g. "url:/confirmation"
    screenshots: list[str] = field(default_factory=list)
    answers: list[Answer] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return self.state in (AttemptState.SUBMITTED, AttemptState.READY_TO_SUBMIT)
