@dataclass(frozen=True)
class Option:
    label: str            # verbatim, as the owner would read it
    value: str = ""       # the site's own value (Greenhouse option id, select value); "" if none


@dataclass(frozen=True)
class FormField:
    """One input the site asks for.

    `key` is unique within a FormPlan and stable for one posting: the
    Greenhouse field name, the Lever card path, the Workday automation id plus
    an index, or an id the adapter derives from the DOM.
    """
    key: str
    label: str                              # verbatim question text
    type: FieldType
    required: bool = False
    options: tuple[Option, ...] = ()
    step: str = ""                          # wizard step id; "" on single-page forms
    section: str = ""                       # e.g. questions | location | compliance | demographic | data_compliance | eeo | consent
    description: str = ""                   # help text under the label (plain text)
    max_length: Optional[int] = None
    canonical: Optional[Canonical] = None   # set only for tier-1 fields
    locator: str = ""                       # adapter-private hint for finding it again (CSS); never shown
    alt_of: str = ""                        # this field is an alternative input for `alt_of` (e.g. resume_text for resume)


@dataclass
class FormPlan:
    ats: str
    job_id: str
    apply_url: str
    source: str                             # "schema" (built before the browser) | "dom"
    fields: list[FormField] = field(default_factory=list)
    steps: tuple[str, ...] = ()             # known wizard steps in order; () for one page

    def by_key(self) -> dict[str, FormField]:
        return {f.key: f for f in self.fields}


