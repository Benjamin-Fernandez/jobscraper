class ApplyFailure(Exception):
    """Raised by any apply component to end the attempt with a reason.

    `detail` must contain no personal value (no answer, email or password):
    it is logged and shown. A question label or a field name is fine.
    """

    def __init__(self, reason: ReasonCode, detail: str = "", *, step: str = ""):
        super().__init__(f"{reason.value}: {detail}" if detail else reason.value)
        self.reason = reason
        self.detail = detail
        self.step = step


